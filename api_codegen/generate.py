from __future__ import annotations

import re
import subprocess
import textwrap
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml
from jinja2 import Environment, FileSystemLoader, StrictUndefined

Schema = dict[str, Any]
TEMPLATE_DIR = Path(__file__).with_name("templates")
ROOT = Path(__file__).resolve().parents[1]
DEFAULT_CONFIG = ROOT / "api" / "codegen.yaml"
TEMPLATES = Environment(
    loader=FileSystemLoader(TEMPLATE_DIR),
    undefined=StrictUndefined,
    autoescape=False,
    keep_trailing_newline=True,
    trim_blocks=True,
    lstrip_blocks=True,
)
GENERATED_MARKER = "// Generated by `make api-generate`. Do not edit."
CONFIG = yaml.safe_load(DEFAULT_CONFIG.read_text(encoding="utf-8"))
TYPE_CONFIG = CONFIG.get("types", {})
API_CONFIG = CONFIG.get("api", {})


@dataclass(frozen=True)
class GeneratedCount:
    objects: int
    methods: int


@dataclass(frozen=True)
class ConstantModel:
    name: str
    value: str


@dataclass(frozen=True)
class FieldModel:
    wire_name: str
    cpp_name: str
    cpp_type: str
    required: bool
    description: tuple[str, ...]
    constant: ConstantModel | None
    enum: EnumModel | None


@dataclass(frozen=True)
class EnumValueModel:
    name: str
    value: str


@dataclass(frozen=True)
class EnumModel:
    name: str
    values: tuple[EnumValueModel, ...]


@dataclass(frozen=True)
class ObjectModel:
    name: str
    description: tuple[str, ...]
    constants: tuple[ConstantModel, ...]
    enums: tuple[EnumModel, ...]
    fields: tuple[FieldModel, ...]
    union_members: tuple[str, ...]
    dependencies: tuple[str, ...]
    standard_headers: tuple[str, ...]


@dataclass(frozen=True)
class ParameterModel:
    wire_name: str
    cpp_name: str
    cpp_type: str
    declaration_type: str
    required: bool
    always_send: bool
    default_value: str | None
    wire_default_value: str | None
    description: tuple[str, ...]


@dataclass(frozen=True)
class MethodModel:
    name: str
    return_type: str
    response_type: str
    description: tuple[str, ...]
    parameters: tuple[ParameterModel, ...]


def run(schema_path: Path, root: Path) -> None:
    generated = generate_openapi(schema_path, root)
    print(f"Generated {generated.objects} types and {generated.methods} API methods")


def generate_openapi(schema_path: Path, root: Path) -> GeneratedCount:
    document = yaml.safe_load(schema_path.read_text(encoding="utf-8"))
    components = {
        name: schema
        for name, schema in document["components"]["schemas"].items()
        if "x-tags" in schema
    }
    objects = _build_objects(components)
    methods = _build_methods(document["paths"])
    api_objects = _api_objects(methods, objects)
    outputs = {
        root / "include" / "tgbot" / "types" / "types_fwd.h": _render_template(
            "types_fwd.h.j2", objects=objects
        ),
        root / "include" / "tgbot" / "types" / "types.h": _render_template(
            "types.h.j2", objects=objects
        ),
        root / "include" / "tgbot" / "ApiMethods.inc.h": _render_template(
            "api_methods.inc.h.j2", methods=methods
        ),
        root / "src" / "ApiMethods.cpp": _render_template(
            "api_methods.cpp.j2", methods=methods, objects=api_objects
        ),
    }
    type_headers = {
        root / "include" / "tgbot" / "types" / f"{object.name}.h": _render_template(
            "type.h.j2",
            object=object,
        )
        for object in objects
    }
    outputs.update(type_headers)
    type_sources = {
        root / "src" / "types" / f"{object.name}.cpp": _render_template(
            "type.cpp.j2",
            object=object,
        )
        for object in objects
    }
    outputs.update(type_sources)
    expected_type_headers = set(type_headers)
    expected_type_headers.add(root / "include" / "tgbot" / "types" / "types_fwd.h")
    _sync_generated_type_headers(root, expected_type_headers)
    _sync_generated_type_sources(root, set(type_sources))
    for path, content in outputs.items():
        _write(path, content)

    return GeneratedCount(len(objects), len(methods))


def _build_objects(components: dict[str, Schema]) -> tuple[ObjectModel, ...]:
    names = set(components)
    objects = []
    for name in sorted(names):
        schema = components[name]
        required = set(schema.get("required", []))
        union_members = _union_members(name, schema, names)
        fields = tuple(
            _build_field(name, field_name, field, field_name in required)
            for field_name, field in schema.get("properties", {}).items()
        )
        objects.append(
            ObjectModel(
                name=name,
                description=_comment_lines(schema.get("description", ""), 92),
                constants=_object_constants(fields),
                enums=tuple(field.enum for field in fields if field.enum),
                fields=fields,
                union_members=union_members,
                dependencies=_object_dependencies(name, fields, union_members, names),
                standard_headers=_object_standard_headers(fields, union_members),
            )
        )

    return tuple(objects)


def _build_field(
    object_name: str, name: str, schema: Schema, required: bool
) -> FieldModel:
    enum = _field_enum(object_name, name)
    field_config = TYPE_CONFIG.get(object_name, {}).get("fields", {}).get(name, {})
    cpp_type = field_config.get(
        "type", enum.name if enum else _field_type(name, schema, required)
    )
    return FieldModel(
        wire_name=name,
        cpp_name=_snake_to_camel(name),
        cpp_type=cpp_type,
        required=required,
        description=_comment_lines(schema.get("description", ""), 88),
        constant=_field_constant(name, schema, required),
        enum=enum,
    )


def _field_enum(object_name: str, field_name: str) -> EnumModel | None:
    values = (
        TYPE_CONFIG.get(object_name, {})
        .get("fields", {})
        .get(field_name, {})
        .get("enum")
    )
    if not values:
        return None

    return EnumModel(
        name="Type",
        values=tuple(
            EnumValueModel(name=name, value=value) for name, value in values.items()
        ),
    )


def _object_constants(fields: tuple[FieldModel, ...]) -> tuple[ConstantModel, ...]:
    return tuple(field.constant for field in fields if field.constant)


def _api_objects(
    methods: tuple[MethodModel, ...], objects: tuple[ObjectModel, ...]
) -> tuple[ObjectModel, ...]:
    object_names = {object.name for object in objects}
    cpp_types = [method.return_type for method in methods]
    cpp_types.extend(
        parameter.cpp_type for method in methods for parameter in method.parameters
    )
    used_names = {
        token
        for cpp_type in cpp_types
        for token in re.findall(r"\b[A-Z][A-Za-z0-9]*\b", cpp_type)
        if token in object_names
    }

    return tuple(object for object in objects if object.name in used_names)


def _object_dependencies(
    name: str,
    fields: tuple[FieldModel, ...],
    union_members: tuple[str, ...],
    object_names: set[str],
) -> tuple[str, ...]:
    cpp_types = [field.cpp_type for field in fields]
    cpp_types.extend(union_members)
    dependencies = {
        token
        for cpp_type in cpp_types
        for token in re.findall(r"\b[A-Z][A-Za-z0-9]*\b", cpp_type)
        if token in object_names and token != name
    }

    return tuple(sorted(dependencies))


def _object_standard_headers(
    fields: tuple[FieldModel, ...], union_members: tuple[str, ...]
) -> tuple[str, ...]:
    cpp_types = " ".join(field.cpp_type for field in fields)
    headers = {"memory"}
    for cpp_type, header in (
        ("std::int", "cstdint"),
        ("std::optional", "optional"),
        ("std::string", "string"),
        ("std::variant", "variant"),
        ("std::vector", "vector"),
    ):
        if cpp_type in cpp_types:
            headers.add(header)
    if union_members:
        headers.add("variant")

    return tuple(sorted(headers))


def _build_methods(paths: dict[str, Schema]) -> tuple[MethodModel, ...]:
    methods = []
    for path in sorted(paths):
        operation = paths[path]["post"]
        name = operation["operationId"]
        request = _request_schema(operation)
        multipart = _multipart_schema(operation)
        properties = dict(request.get("properties", {}))
        for parameter_name, parameter in multipart.get("properties", {}).items():
            properties.setdefault(parameter_name, parameter)
        required = set(request.get("required", [])) | set(multipart.get("required", []))
        binary = _binary_parameters(operation)
        parameter_names = _ordered_parameter_names(name, properties, required)
        response_type = _api_cpp_type(_response_schema(operation))
        method_config = API_CONFIG.get(name, {})
        methods.append(
            MethodModel(
                name=name,
                return_type=method_config.get("return_type", response_type),
                response_type=response_type,
                description=_comment_lines(operation.get("description", ""), 88),
                parameters=tuple(
                    _build_parameter(
                        name,
                        parameter_name,
                        properties[parameter_name],
                        parameter_name in required,
                        parameter_name in binary,
                    )
                    for parameter_name in parameter_names
                ),
            )
        )

    return tuple(methods)


def _ordered_parameter_names(
    method_name: str, properties: dict[str, Schema], required: set[str]
) -> list[str]:
    method_config = API_CONFIG.get(method_name, {})
    preferred = method_config.get("parameter_order", ())
    parameter_order = {name: index for index, name in enumerate(preferred)}
    declaration_required = required | {
        name
        for name in properties
        if method_config.get("parameters", {}).get(name, {}).get("declaration_required")
    }
    required_names = sorted(
        (name for name in properties if name in declaration_required),
        key=lambda name: (
            name != "chat_id",
            parameter_order.get(name, len(parameter_order)),
            name,
        ),
    )
    optional_names = [name for name in properties if name not in declaration_required]
    optional_names.sort(
        key=lambda name: (parameter_order.get(name, len(parameter_order)), name)
    )

    return required_names + optional_names


def _build_parameter(
    method_name: str, name: str, schema: Schema, required: bool, binary: bool
) -> ParameterModel:
    parameter_config = (
        API_CONFIG.get(method_name, {}).get("parameters", {}).get(name, {})
    )
    override = parameter_config.get("type")
    if override:
        cpp_type = override
    elif name in {"chat_id", "from_chat_id"}:
        cpp_type = "std::variant<std::int64_t, std::string>"
    elif name == "certificate" and binary:
        cpp_type = "InputFile::Ptr"
    elif binary:
        cpp_type = "std::variant<InputFile::Ptr, std::string>"
    else:
        cpp_type = _api_cpp_type(schema)
        cpp_type = _telegram_integer_type(name, cpp_type)
    return ParameterModel(
        wire_name=name,
        cpp_name=_snake_to_camel(name),
        cpp_type=cpp_type,
        declaration_type=_parameter_declaration_type(cpp_type),
        required=required,
        always_send=bool(parameter_config.get("always_send")),
        default_value=(
            None
            if required or parameter_config.get("declaration_required")
            else _parameter_default(cpp_type, method_name, name)
        ),
        wire_default_value=(
            None
            if parameter_config.get("always_send")
            else _configured_parameter_default(method_name, name)
        ),
        description=_comment_lines(schema.get("description", ""), 72),
    )


def _parameter_declaration_type(cpp_type: str) -> str:
    if cpp_type == "std::string" or cpp_type.startswith("std::vector<"):
        return f"const {cpp_type}&"
    if cpp_type == "nlohmann::json":
        return "const nlohmann::json&"

    return cpp_type


def _parameter_default(cpp_type: str, method_name: str, parameter_name: str) -> str:
    if (
        default := _configured_parameter_default(method_name, parameter_name)
    ) is not None:
        return default
    if cpp_type == "bool":
        return "false"
    if cpp_type in {"std::int32_t", "std::int64_t", "double"}:
        return "0"
    if cpp_type == "std::string":
        return '""'
    if cpp_type.startswith("std::shared_ptr<") or cpp_type.endswith("::Ptr"):
        return "nullptr"
    if cpp_type == "nlohmann::json":
        return "nullptr"

    return "{ }"


def _configured_parameter_default(method_name: str, parameter_name: str) -> str | None:
    parameter_config = (
        API_CONFIG.get(method_name, {}).get("parameters", {}).get(parameter_name, {})
    )
    default = parameter_config.get("default")
    if default is None:
        return None
    if isinstance(default, bool):
        return str(default).lower()

    return str(default)


def _write(path: Path, content: str) -> None:
    content = _format_cpp(path, content)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def _sync_generated_type_headers(root: Path, expected_paths: set[Path]) -> None:
    types_dir = root / "include" / "tgbot" / "types"
    if not types_dir.exists():
        return
    stale_paths = [
        path
        for path in types_dir.glob("*.h")
        if path not in expected_paths
        and path.read_text(encoding="utf-8").startswith(GENERATED_MARKER)
    ]
    for path in stale_paths:
        path.unlink()


def _sync_generated_type_sources(root: Path, expected_paths: set[Path]) -> None:
    types_dir = root / "src" / "types"
    if not types_dir.exists():
        return
    stale_paths = [
        path
        for path in types_dir.glob("*.cpp")
        if path not in expected_paths
        and path.read_text(encoding="utf-8").startswith(GENERATED_MARKER)
    ]
    for path in stale_paths:
        path.unlink()


def _format_cpp(path: Path, content: str) -> str:
    if path.name.endswith(".inc.h"):
        return _format_cpp_class_fragment(path, content)

    return _run_clang_format(path, content)


def _format_cpp_class_fragment(path: Path, content: str) -> str:
    marker, separator, body = content.partition("\n\n")
    if not separator:
        raise ValueError(f"Generated C++ fragment {path} has no marker")
    wrapped = f"class Api {{\npublic:\n{body}}};\n"
    formatted = _run_clang_format(path, wrapped)
    body_start = formatted.index("public:\n") + len("public:\n")
    body_end = formatted.rindex("\n};")

    return f"{marker}\n\n{formatted[body_start:body_end]}\n"


def _run_clang_format(path: Path, content: str) -> str:
    process = subprocess.run(
        ["clang-format", f"--assume-filename={path.name}"],
        input=content,
        text=True,
        capture_output=True,
        check=True,
    )

    return process.stdout


def _render_template(name: str, **context: Any) -> str:
    return TEMPLATES.get_template(name).render(**context)


def _request_schema(operation: Schema) -> Schema:
    return (
        operation.get("requestBody", {})
        .get("content", {})
        .get("application/json", {"schema": {"type": "object", "properties": {}}})[
            "schema"
        ]
    )


def _multipart_schema(operation: Schema) -> Schema:
    return (
        operation.get("requestBody", {})
        .get("content", {})
        .get("multipart/form-data", {"schema": {}})["schema"]
    )


def _binary_parameters(operation: Schema) -> set[str]:
    multipart = (
        operation.get("requestBody", {})
        .get("content", {})
        .get("multipart/form-data", {})
    )

    return {
        name
        for name, schema in multipart.get("schema", {}).get("properties", {}).items()
        if schema.get("format") == "binary"
    }


def _response_schema(operation: Schema) -> Schema:
    response = operation["responses"]["200"]["content"]["application/json"]["schema"]
    for part in response.get("allOf", []):
        if result := part.get("properties", {}).get("result"):
            return result

    raise ValueError(f"Response type is missing for {operation['operationId']}")


def _field_type(name: str, schema: Schema, required: bool) -> str:
    result = _telegram_integer_type(name, _cpp_type(schema))
    if required or result.startswith("std::shared_ptr<"):
        return result

    return f"std::optional<{result}>"


def _field_constant(name: str, schema: Schema, required: bool) -> ConstantModel | None:
    if not required or name not in {"source", "status", "type"}:
        return None
    if schema.get("type") != "string":
        return None

    values = schema.get("enum", [])
    if len(values) == 1:
        return ConstantModel(name.upper(), str(values[0]))

    description = schema.get("description", "")
    for pattern in (
        r"\bmust be ([a-z0-9_]+)(?:[.,]|$)",
        r"\balways [\"“]([a-z0-9_]+)[\"”]",
    ):
        if match := re.search(pattern, description):
            return ConstantModel(name.upper(), match.group(1))

    return None


def _api_cpp_type(schema: Schema) -> str:
    if name := _ref_name(schema):
        return f"std::shared_ptr<{name}>"
    if choices := schema.get("oneOf"):
        return f"std::variant<{', '.join(_api_cpp_type(item) for item in choices)}>"
    if schema.get("type") == "array":
        return f"std::vector<{_api_cpp_type(schema['items'])}>"

    return _cpp_type(schema)


def _cpp_type(schema: Schema) -> str:
    if name := _ref_name(schema):
        return f"std::shared_ptr<{name}>"
    if choices := schema.get("oneOf"):
        return f"std::variant<{', '.join(_cpp_type(item) for item in choices)}>"
    schema_type = schema.get("type")
    if schema_type == "array":
        return f"std::vector<{_cpp_type(schema['items'])}>"
    if schema_type == "boolean":
        return "bool"
    if schema_type == "integer":
        return "std::int64_t" if schema.get("format") == "int64" else "std::int32_t"
    if schema_type == "number":
        return "double"
    if schema_type == "string":
        return "std::string"

    return "nlohmann::json"


def _telegram_integer_type(name: str, cpp_type: str) -> str:
    wide_id = name in {
        "user_id",
        "chat_id",
        "direct_messages_topic_id",
    } or name.endswith(("_user_id", "_chat_id"))
    if wide_id and cpp_type == "std::int32_t":
        return "std::int64_t"

    return cpp_type


def _union_members(name: str, schema: Schema, names: set[str]) -> tuple[str, ...]:
    if schema.get("properties"):
        return ()

    return tuple(
        dict.fromkeys(
            line.strip()
            for line in schema.get("description", "").splitlines()
            if line.strip() in names and line.strip() != name
        )
    )


def _ref_name(schema: Schema) -> str | None:
    if ref := schema.get("$ref"):
        return str(ref).rsplit("/", 1)[-1]
    for item in schema.get("allOf", []):
        if name := _ref_name(item):
            return name

    return None


def _comment_lines(text: str, width: int) -> tuple[str, ...]:
    normalized = " ".join(text.replace("*/", "* /").split())
    if not normalized:
        return ()

    return tuple(textwrap.wrap(normalized, width=width, break_long_words=False))


def _snake_to_camel(value: str) -> str:
    first, *rest = value.split("_")

    return first + "".join(part[:1].upper() + part[1:] for part in rest)
